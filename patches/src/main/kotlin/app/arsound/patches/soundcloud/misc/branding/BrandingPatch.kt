import java.io.File

private val DENSITIES = listOf("mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi")
private val ARTWORK_PLACEHOLDER_NAMES = listOf("ic_default_playable_artwork_placeholder", "ic_default_playable_artwork_placeholder_dark")
private val LOGO_NAMES = listOf("ic_logo_cloud", "ic_logo_cloud_active", "ic_logo_cloud_dark", "ic_logo_cloud_light", "ic_logo_cloud_launcher")
private val LAUNCHER_FOREGROUND_NAMES = listOf(
    "ic_launcher_foreground", "ic_launcher_foreground_black", "ic_launcher_foreground_orange", "ic_launcher_foreground_white",
)

/** The resource folders whose name starts with [prefix] (drawable, drawable-night-nodpi, ...). */
private fun File.resFolders(prefix: String): Array<File> =
    listFiles { file -> file.isDirectory && file.name.startsWith(prefix) }!!

/** The colours of SoundCloud's resources: name to value, a value being a colour or a reference to another one. */
private fun soundCloudColors(file: File): Map<String, String> =
    Regex("<color name=\"([^\"]+)\">([^<]+)</color>").findAll(file.readText())
        .associate { it.groupValues[1] to it.groupValues[2].trim() }

/** Replaces the colour references of a drawable with the colours they stand for, following references. */
private fun withColorValues(text: String, colors: Map<String, String>): String =
    Regex("@color/([a-z0-9_]+)").replace(text) { match ->
        var value = match.value
        repeat(10) {
            if (!value.startsWith("@color/")) return@repeat
            value = colors[value.removePrefix("@color/")] ?: return@replace match.value
        }
        if (value.startsWith("#")) value else match.value
    }

/**
 * Arsound branding: Replaces the launcher icon, the start animation and the SoundCloud logo icons with the Arsound icon.
 * Part of the "Arsound" patch, not shown on its own.
 *
 * Resources are generated by tools/branding/generate.py from the exported icon set. The steps depend on the state the
 * earlier ones leave in res, so their order is fixed.
 */
val brandingPatch = resourcePatch {
    compatibleWith("com.soundcloud.android")

    apply {
        copyArsoundFiles()
        val res = get("res")
        removeExtraNightAnimations(res)
        // Before the replacements below: they overwrite the SoundCloud files that are copied here.
        val soundCloudIcons = copySoundCloudIcons(res)
        replaceLauncherIcons(res)
        replaceLogosAndPlaceholders(res)
        copyAppIcons()
        document("AndroidManifest.xml").use { document -> document.addLauncherAliases(soundCloudIcons) }
        showDrawingLetterAtStart(res)
        // After the step above, which would turn the 0 of this style into the time of the letter's drawing.
        addSoundCloudStartTheme()
    }
}

/** The Arsound launcher foreground, the start animation (an animated vector) and the icon of every density. */
private fun ResourcePatchContext.copyArsoundFiles() = copyResources(
    "soundcloud/branding",
    ResourceGroup("drawable-nodpi", "arsound_launcher_foreground.png"),
    ResourceGroup("drawable", "arsound_splash.xml"),
    *DENSITIES
        .map { ResourceGroup("drawable-$it", "arsound_icon.png") }
        .toTypedArray(),
)

/** The decoded night variant may be named raw-night-v8; keep a single night file. */
private fun removeExtraNightAnimations(res: File) {
    res.listFiles { file -> file.isDirectory && file.name.startsWith("raw-night") && file.name != "raw-night" }!!
        .forEach { it.resolve("loading_animation.json").delete() }
}

/**
 * SoundCloud's own icons are copied under names of their own for the picker, before the branding replaces them: the
 * adaptive icons and the cloud foregrounds they draw. Their colours are written in as values: the orange is the accent
 * colour, which the Arsound theme repaints inside the app, so the picker would show a pink "orange" icon while the
 * launcher shows the real one. The bitmap layers of the patterned icons keep their names, nothing replaces them.
 *
 * Returns the ids of the icons that were copied.
 */
private fun copySoundCloudIcons(res: File): List<String> {
    val colors = soundCloudColors(res.resolve("values/colors.xml"))
    fun copyDrawable(name: String, copy: String) =
        res.resFolders("drawable")
            .map { it.resolve("$name.xml") }
            .filter { it.exists() }
            .onEach { it.resolveSibling("$copy.xml").writeText(withColorValues(it.readText(), colors)) }
            .isNotEmpty()
    res.resolve("drawable").listFiles { file -> file.name.startsWith(SOUNDCLOUD_FOREGROUND) && file.name.endsWith(".xml") }!!
        .forEach { copyDrawable(it.nameWithoutExtension, it.nameWithoutExtension.replaceFirst(SOUNDCLOUD_FOREGROUND, SOUNDCLOUD_FOREGROUND_COPY)) }
    // The cloud of SoundCloud's notifications, which the extension puts back for a user of one of SoundCloud's icons
    // (BrandMark.mark). The picture at the start of the app needs the orange foreground copied above.
    if (!copyDrawable(SOUNDCLOUD_NOTIFICATION_ICON, SOUNDCLOUD_NOTIFICATION_ICON_COPY)) {
        throw PatchException("SoundCloud has no notification icon $SOUNDCLOUD_NOTIFICATION_ICON any more")
    }
    if (!res.resolve("drawable/$SOUNDCLOUD_START_ICON.xml").exists()) {
        throw PatchException("SoundCloud's start picture $SOUNDCLOUD_START_ICON was not copied")
    }
    return SOUNDCLOUD_APP_ICONS.filter { (source, id) ->
        val copies = res.resFolders("mipmap-anydpi")
            .mapNotNull { directory ->
                val icon = directory.resolve("$source.xml")
                if (!icon.exists()) return@mapNotNull null
                var text = icon.readText().replace("@drawable/$SOUNDCLOUD_FOREGROUND", "@drawable/$SOUNDCLOUD_FOREGROUND_COPY")
                // Vector and shape backgrounds get copies with the colour values too.
                Regex("@drawable/(ic_launcher_[a-z0-9_]*background)").findAll(text).map { it.groupValues[1] }.toSet()
                    .forEach { background ->
                        if (copyDrawable(background, "arsound_sc_$background")) {
                            text = text.replace("@drawable/$background\"", "@drawable/arsound_sc_$background\"")
                        }
                    }
                directory.resolve("arsound_icon_$id.xml").writeText(text)
            }
        // A later SoundCloud version may drop an icon; the picker leaves out variants without a picture.
        copies.isNotEmpty()
    }.map { it.second }
}

/** Every launcher icon, including the alternative app icons users can pick in SoundCloud. */
private fun replaceLauncherIcons(res: File) {
    res.resFolders("mipmap-anydpi")
        .flatMap { directory -> directory.listFiles { file -> file.name.startsWith("ic_launcher") }!!.toList() }
        .forEach { icon ->
            icon.writeText(
                """
                <?xml version="1.0" encoding="utf-8"?>
                <adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
                    <background android:drawable="@android:color/black" />
                    <foreground android:drawable="@drawable/arsound_launcher_foreground" />
                    <monochrome android:drawable="@drawable/arsound_launcher_foreground" />
                </adaptive-icon>
                """.trimIndent(),
            )
        }
}

/**
 * SoundCloud logo spots: its vectors in every density folder are removed and replaced by letter vectors
 * with the same names, sizes and colours, so the 88dp logo on the sign-in screen stays sharp.
 * The launcher foregrounds become PNGs, because Compose screens cannot draw bitmap XML. The track artwork
 * placeholder becomes bitmaps instead of vectors, see tools/branding/generate.py.
 */
private fun ResourcePatchContext.replaceLogosAndPlaceholders(res: File) {
    fun removeDrawables(names: List<String>) = res.resFolders("drawable")
        .flatMap { directory ->
            directory.listFiles { file -> file.name.endsWith(".xml") && file.nameWithoutExtension in names }!!.toList()
        }
        .forEach { it.delete() }
    removeDrawables(LOGO_NAMES + LAUNCHER_FOREGROUND_NAMES)
    removeDrawables(ARTWORK_PLACEHOLDER_NAMES)
    copyResources(
        "soundcloud/branding",
        ResourceGroup("drawable", *LOGO_NAMES.map { "$it.xml" }.toTypedArray()),
        ResourceGroup("drawable-nodpi", *ARTWORK_PLACEHOLDER_NAMES.map { "$it.png" }.toTypedArray()),
        ResourceGroup("drawable-night-nodpi", "ic_default_playable_artwork_placeholder.png"),
        ResourceGroup("drawable-nodpi", *LAUNCHER_FOREGROUND_NAMES.map { "$it.png" }.toTypedArray()),
        // The loading animation of the whole app (Lottie): the letter being drawn instead of the cloud.
        ResourceGroup("raw", "loading_animation.json"),
        ResourceGroup("raw-night", "loading_animation.json"),
    )
}

/** The files of the app icon variants (tools/branding/icons.py). */
private fun ResourcePatchContext.copyAppIcons() = copyResources(
    "soundcloud/branding",
    ResourceGroup(
        "drawable",
        *APP_ICONS.filter { it !in BITMAP_APP_ICONS }
            .flatMap { listOf("arsound_icon_bg_$it.xml", "arsound_icon_fg_$it.xml") }.toTypedArray(),
    ),
    // Glowing, neon and art icons: their layers are bitmaps.
    ResourceGroup(
        "drawable-nodpi",
        *BITMAP_APP_ICONS.flatMap { listOf("arsound_icon_bg_$it.webp", "arsound_icon_fg_$it.webp") }.toTypedArray(),
    ),
    ResourceGroup("mipmap-anydpi", *APP_ICONS.map { "arsound_icon_$it.xml" }.toTypedArray()),
)

/**
 * Each app icon variant is a launcher entry: an alias of the start screen, only the default enabled. The start screen
 * itself loses its launcher entry, so switching the icon never disables it (links and the app restart open it directly).
 */
private fun Document.addLauncherAliases(soundCloudIcons: List<String>) {
    val launcher = getElementsByTagName("activity").asSequence().map { it as Element }
        .first { it.getAttribute("android:name") == "com.soundcloud.android.launcher.LauncherActivity" }
    launcher.getElementsByTagName("intent-filter").asSequence().map { it as Element }.toList()
        .filter { filter ->
            filter.getElementsByTagName("category").asSequence()
                .any { (it as Element).getAttribute("android:name") == "android.intent.category.LAUNCHER" }
        }
        .forEach { launcher.removeChild(it) }

    var anchor: Node = launcher
    (APP_ICONS + soundCloudIcons).forEachIndexed { index, id ->
        val alias = createElement("activity-alias")
        alias.setAttribute("android:name", "com.soundcloud.android.launcher.ArsoundIcon_$id")
        alias.setAttribute("android:targetActivity", "com.soundcloud.android.launcher.LauncherActivity")
        alias.setAttribute("android:enabled", (index == 0).toString())
        alias.setAttribute("android:exported", "true")
        alias.setAttribute("android:icon", "@mipmap/arsound_icon_$id")
        alias.setAttribute("android:roundIcon", "@mipmap/arsound_icon_$id")
        val filter = createElement("intent-filter")
        filter.appendChild(createElement("action").apply { setAttribute("android:name", "android.intent.action.MAIN") })
        filter.appendChild(createElement("category").apply { setAttribute("android:name", "android.intent.category.LAUNCHER") })
        alias.appendChild(filter)
        launcher.parentNode.insertBefore(alias, anchor.nextSibling)
        anchor = alias
    }
}

/**
 * The start screen for a user of one of SoundCloud's icons: SoundCloud's own start theme with its own picture, the
 * orange cloud, which stands still as in SoundCloud. A launcher entry cannot have a theme of its own, so the app hands
 * this style to Android when such an icon is chosen (`SplashStyle` in the extension), like the start screens of the
 * themes; Android 13 and later keep it for the next starts.
 */
private fun ResourcePatchContext.addSoundCloudStartTheme() {
    document("res/values/styles.xml").use { document ->
        val style = document.createElement("style")
        style.setAttribute("name", SOUNDCLOUD_START_THEME)
        style.setAttribute("parent", "@style/SoundcloudAppTheme.SplashScreen")
        mapOf(
            "windowSplashScreenAnimatedIcon" to "@drawable/$SOUNDCLOUD_START_ICON",
            "windowSplashScreenAnimationDuration" to "0",
        ).forEach { (name, value) ->
            style.appendChild(
                document.createElement("item").apply {
                    setAttribute("name", name)
                    textContent = value
                },
            )
        }
        document.getElementsByTagName("resources").item(0).appendChild(style)
    }
}

/** The start screen shows the А9 mark drawing itself instead of the orange cloud; the drawing takes 1.5 s. */
private fun ResourcePatchContext.showDrawingLetterAtStart(res: File) {
    res.resFolders("values")
        .filter { it.resolve("styles.xml").exists() }
        .forEach { directory ->
            document("res/${directory.name}/styles.xml").use { document ->
                document.getElementsByTagName("item").asSequence().map { it as Element }.forEach { item ->
                    when (item.getAttribute("name")) {
                        "windowSplashScreenAnimatedIcon", "android:windowSplashScreenAnimatedIcon" ->
                            if (item.textContent.startsWith("@drawable/ic_launcher_foreground")) {
                                item.textContent = "@drawable/arsound_splash"
                            }
                        "windowSplashScreenAnimationDuration" ->
                            if (item.textContent == "0") item.textContent = "1500"
                    }
                }
            }
        }
}
